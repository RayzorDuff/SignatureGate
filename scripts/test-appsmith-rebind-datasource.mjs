#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';

const script = path.resolve(new URL('./appsmith-rebind-datasource.mjs', import.meta.url).pathname);
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'appsmith-rebind-'));
const q1 = path.join(root, 'pages', 'A', 'queries', 'q1', 'metadata.json');
const q2 = path.join(root, 'pages', 'B', 'nested', 'queries', 'q2', 'metadata.json');
fs.mkdirSync(path.dirname(q1), { recursive: true });
fs.mkdirSync(path.dirname(q2), { recursive: true });
fs.mkdirSync(path.join(root, 'datasources'), { recursive: true });
fs.writeFileSync(path.join(root, 'datasources', 'signaturegate-postgres-test.json'), '{"name":"signaturegate-postgres-test","pluginId":"postgres-plugin"}\n');
fs.writeFileSync(path.join(root, 'datasources', 'signaturegate-postgres.json'), '{"name":"signaturegate-postgres","pluginId":"postgres-plugin"}\n');

const q1Original = '{\n  "id": "q1",\n  "unpublishedAction": {\n    "actionConfiguration": { "body": "SELECT 1" },\n    "datasource": {\n      "id": "signaturegate-postgres-test",\n      "isAutoGenerated": false,\n      "name": "signaturegate-postgres-test",\n      "pluginId": "postgres-plugin"\n    },\n    "name": "q1"\n  }\n}\n';
const q2Original = '{"id":"q2","unpublishedAction":{"datasource":{"name":"signaturegate-postgres-test","id":"signaturegate-postgres-test","pluginId":"postgres-plugin"},"x":{"a":1}}}\n';
fs.writeFileSync(q1, q1Original);
fs.writeFileSync(q2, q2Original);

function run(...args) {
  return spawnSync(process.execPath, [script, '--source', root, ...args], { encoding: 'utf8' });
}
function hash(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

let result = run('--from', 'signaturegate-postgres-test', '--to', 'signaturegate-postgres');
assert.equal(result.status, 0, result.stderr);
assert.match(result.stdout, /"referencesChanged": 2/);
assert.match(fs.readFileSync(q1, 'utf8'), /"id": "signaturegate-postgres"/);
assert.match(fs.readFileSync(q1, 'utf8'), /"name": "signaturegate-postgres"/);
assert.match(fs.readFileSync(q2, 'utf8'), /"name":"signaturegate-postgres","id":"signaturegate-postgres"/);

result = run('--verify', '--expected-datasource', 'signaturegate-postgres');
assert.equal(result.status, 0, result.stderr);
assert.match(result.stdout, /"unexpected": \[\]/);

const afterFirst = fs.readFileSync(q1, 'utf8');
result = run('--from', 'signaturegate-postgres-test', '--to', 'signaturegate-postgres');
assert.equal(result.status, 0, result.stderr);
assert.match(result.stdout, /"referencesChanged": 0/);
assert.equal(fs.readFileSync(q1, 'utf8'), afterFirst);

result = run('--from', 'signaturegate-postgres', '--to', 'signaturegate-postgres-test');
assert.equal(result.status, 0, result.stderr);
assert.equal(fs.readFileSync(q1, 'utf8'), q1Original);
assert.equal(fs.readFileSync(q2, 'utf8'), q2Original);

fs.writeFileSync(q2, '{not-json}\n');
const beforeMalformed = hash(q1);
result = run('--from', 'signaturegate-postgres-test', '--to', 'signaturegate-postgres');
assert.notEqual(result.status, 0);
assert.match(result.stderr, /malformed JSON/);
assert.equal(hash(q1), beforeMalformed);

fs.writeFileSync(q2, q2Original);
fs.writeFileSync(q1, q1Original.replaceAll('signaturegate-postgres-test', 'unexpected-datasource'));
result = run('--verify', '--expected-datasource', 'signaturegate-postgres-test');
assert.notEqual(result.status, 0);
assert.match(result.stdout, /unexpected-datasource/);

console.log(JSON.stringify({ ok: true, cases: 5 }, null, 2));
